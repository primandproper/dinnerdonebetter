func TestServiceImpl_RegisterDeviceToken(t *testing.T) {
	t.Parallel()

	t.Run("success", func(t *testing.T) {
		t.Parallel()

		ctx := t.Context()

		fakeToken := notificationsfakes.BuildFakeUserDeviceToken()

		mockRepo := &notificationsmock.RepositoryMock{
			CreateUserDeviceTokenFunc: func(_ context.Context, input *notifications.UserDeviceTokenDatabaseCreationInput) (*notifications.UserDeviceToken, error) {
				assert.NotNil(t, input)

				return fakeToken, nil
			},
		}
		service := buildTestService(t, mockRepo)

		request := &notificationssvc.RegisterDeviceTokenRequest{
			Input: &notificationssvc.UserDeviceTokenCreationRequestInput{
				DeviceToken: fakeToken.DeviceToken,
				Platform:    fakeToken.Platform,
			},
		}

		response, err := service.RegisterDeviceToken(ctx, request)

		assert.NoError(t, err)
		assert.NotNil(t, response)
		assert.NotNil(t, response.ResponseDetails)
		assert.NotNil(t, response.Created)
		assert.Equal(t, fakeToken.DeviceToken, response.Created.DeviceToken)
		assert.Equal(t, fakeToken.Platform, response.Created.Platform)
		// ID is generated by handler, so we just check it's set
		assert.NotEmpty(t, response.Created.Id)

		assert.Len(t, mockRepo.CreateUserDeviceTokenCalls(), 1)
	})

	t.Run("session context error", func(t *testing.T) {
		t.Parallel()

		ctx := t.Context()
		service := buildTestServiceWithSessionError(t)

		request := &notificationssvc.RegisterDeviceTokenRequest{
			Input: &notificationssvc.UserDeviceTokenCreationRequestInput{
				DeviceToken: "token",
				Platform:    notifications.UserDeviceTokenPlatformIOS,
			},
		}

		response, err := service.RegisterDeviceToken(ctx, request)

		assert.Error(t, err)
		assert.Nil(t, response)
		assert.Equal(t, codes.Unauthenticated, status.Code(err))
	})

	t.Run("nil input", func(t *testing.T) {
		t.Parallel()

		ctx := t.Context()
		mockRepo := &notificationsmock.RepositoryMock{}
		service := buildTestService(t, mockRepo)

		request := &notificationssvc.RegisterDeviceTokenRequest{}

		response, err := service.RegisterDeviceToken(ctx, request)

		assert.Error(t, err)
		assert.Nil(t, response)
		assert.Equal(t, codes.InvalidArgument, status.Code(err))
		assert.Empty(t, mockRepo.CreateUserDeviceTokenCalls())
	})

	t.Run("repository error", func(t *testing.T) {
		t.Parallel()

		ctx := t.Context()

		mockRepo := &notificationsmock.RepositoryMock{
			CreateUserDeviceTokenFunc: func(_ context.Context, _ *notifications.UserDeviceTokenDatabaseCreationInput) (*notifications.UserDeviceToken, error) {
				return nil, errors.New("repository error")
			},
		}
		service := buildTestService(t, mockRepo)

		request := &notificationssvc.RegisterDeviceTokenRequest{
			Input: &notificationssvc.UserDeviceTokenCreationRequestInput{
				DeviceToken: "token",
				Platform:    notifications.UserDeviceTokenPlatformIOS,
			},
		}

		response, err := service.RegisterDeviceToken(ctx, request)

		assert.Error(t, err)
		assert.Nil(t, response)
		assert.Equal(t, codes.Internal, status.Code(err))

		assert.Len(t, mockRepo.CreateUserDeviceTokenCalls(), 1)
	})
}

