func TestServiceImpl_GetUserDeviceTokens(t *testing.T) {
	t.Parallel()

	t.Run("success", func(t *testing.T) {
		t.Parallel()

		ctx := t.Context()

		fakeTokens := notificationsfakes.BuildFakeUserDeviceTokensList()
		pageSize := uint8(20)
		filter := &filtering.QueryFilter{
			MaxResponseSize: &pageSize,
		}

		mockRepo := &notificationsmock.RepositoryMock{
			GetUserDeviceTokensFunc: func(_ context.Context, userID string, actualFilter *filtering.QueryFilter, platformFilter *string) (*filtering.QueryFilteredResult[notifications.UserDeviceToken], error) {
				assert.Equal(t, testSessionUserID, userID)
				assert.NotNil(t, actualFilter)
				assert.Nil(t, platformFilter)

				return fakeTokens, nil
			},
		}
		service := buildTestService(t, mockRepo)

		grpcPageSize := uint32(*filter.MaxResponseSize)
		request := &notificationssvc.GetUserDeviceTokensRequest{
			Filter: &grpcfiltering.QueryFilter{
				MaxResponseSize: &grpcPageSize,
			},
		}

		response, err := service.GetUserDeviceTokens(ctx, request)

		assert.NoError(t, err)
		assert.NotNil(t, response)
		assert.NotNil(t, response.ResponseDetails)
		assert.Len(t, response.Results, len(fakeTokens.Data))

		assert.Len(t, mockRepo.GetUserDeviceTokensCalls(), 1)
	})

	t.Run("session context error", func(t *testing.T) {
		t.Parallel()

		ctx := t.Context()
		service := buildTestServiceWithSessionError(t)

		grpcPageSize := uint32(20)
		request := &notificationssvc.GetUserDeviceTokensRequest{
			Filter: &grpcfiltering.QueryFilter{
				MaxResponseSize: &grpcPageSize,
			},
		}

		response, err := service.GetUserDeviceTokens(ctx, request)

		assert.Error(t, err)
		assert.Nil(t, response)
		assert.Equal(t, codes.Unauthenticated, status.Code(err))
	})
}

